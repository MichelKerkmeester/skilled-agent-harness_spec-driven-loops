// ───────────────────────────────────────────────────────────────────
// MODULE: Sync Vibe Agents
// ───────────────────────────────────────────────────────────────────

'use strict';

// ───────────────────────────────────────────────────────────────────
// 1. IMPORTS
// ───────────────────────────────────────────────────────────────────

const fs = require('node:fs');
const path = require('node:path');
const { parseFrontmatter: parseFrontmatterDoc } = require('@spec-kit/shared/frontmatter/parse-frontmatter.js');
const { findRepoRoot } = require('@spec-kit/shared/workspace/repo-root.mjs');

// ───────────────────────────────────────────────────────────────────
// 2. CONSTANTS
// ───────────────────────────────────────────────────────────────────

const REPO_ROOT = findRepoRoot(__dirname);
const SOURCE_DIR = path.resolve(
  process.env.VIBE_AGENTS_SOURCE_DIR || path.join(REPO_ROOT, '.skilled', 'agents'),
);
const OUTPUT_DIR = path.resolve(
  process.env.VIBE_AGENTS_OUTPUT_DIR || path.join(REPO_ROOT, '.vibe', 'agents'),
);
// Vibe refuses an agent file whose stem is `main`, because hook matching reserves
// that name for the built-in agent.
const RESERVED_STEM = 'main';

// ───────────────────────────────────────────────────────────────────
// 3. HELPERS
// ───────────────────────────────────────────────────────────────────

/** Parses the supported command-line options. */
function parseArguments(argv) {
  if (argv.length === 0) return { check: false };
  if (argv.length === 1 && argv[0] === '--check') return { check: true };
  throw new Error('Usage: node sync-agents-vibe.cjs [--check]');
}

function pathLabel(filePath) {
  const relativePath = path.relative(REPO_ROOT, filePath);
  if (
    relativePath
    && relativePath !== '..'
    && !relativePath.startsWith('..' + path.sep)
    && !path.isAbsolute(relativePath)
  ) {
    return relativePath.split(path.sep).join('/');
  }
  return filePath;
}

/** Lists the agent sources that generate Vibe profiles. */
function listSourceFiles(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md') && entry.name !== 'README.md')
    .map((entry) => entry.name)
    .sort();
}

/** Splits a source into its frontmatter description, its mode and the markdown body after it. */
function splitSource(content, sourcePath) {
  const parsed = parseFrontmatterDoc(content);
  if (parsed.raw === null) {
    throw new Error(sourcePath + ': missing YAML frontmatter');
  }
  const description = parsed.frontmatter.description;
  if (typeof description !== 'string' || description.trim() === '') {
    throw new Error(sourcePath + ': missing frontmatter description');
  }
  const mode = typeof parsed.frontmatter.mode === 'string' ? parsed.frontmatter.mode.trim() : '';
  return { description, mode, body: parsed.body };
}

/** Renders a value as a TOML basic string; JSON escaping is valid TOML escaping. */
function tomlString(value) {
  return JSON.stringify(value);
}

/**
 * Renders one agent profile as a TOML document. Vibe treats a profile with no
 * `agent_type` as a primary agent and refuses to spawn it by name, so a source
 * declared `mode: subagent` carries `agent_type = "subagent"` into its profile.
 */
function renderAgentProfile(fileName, description, mode, body) {
  const lines = [
    '# Generated by sync-agents-vibe.cjs from .skilled/agents/' + fileName + '; do not edit by hand.',
    'description = ' + tomlString(description),
  ];
  if (mode === 'subagent') lines.push('agent_type = ' + tomlString('subagent'));
  lines.push('instructions = ' + tomlString(body));
  return lines.join('\n') + '\n';
}

/** Builds the expected Vibe profiles from the current agent sources. */
function buildExpectedOutputs() {
  const sourceFiles = listSourceFiles(SOURCE_DIR);
  if (sourceFiles.length === 0) {
    throw new Error('no agent sources found in ' + SOURCE_DIR);
  }
  const expected = new Map();
  for (const fileName of sourceFiles) {
    const sourcePath = path.join(SOURCE_DIR, fileName);
    const stem = path.basename(fileName, '.md');
    if (stem.toLowerCase() === RESERVED_STEM) {
      throw new Error(sourcePath + ': Vibe reserves the agent name "' + RESERVED_STEM + '"');
    }
    const { description, mode, body } = splitSource(fs.readFileSync(sourcePath, 'utf8'), sourcePath);
    expected.set(stem + '.toml', {
      sourcePath,
      text: renderAgentProfile(fileName, description, mode, body),
    });
  }
  return expected;
}

function listOutputFiles() {
  if (!fs.existsSync(OUTPUT_DIR)) return [];
  return fs.readdirSync(OUTPUT_DIR, { withFileTypes: true })
    .filter((entry) => entry.name.endsWith('.toml'))
    .map((entry) => entry.name)
    .sort();
}

// A link on the output path below the checkout moves every write and prune
// somewhere else, so each component inside the checkout is judged, not only the
// last one. Above the checkout is the operator's own layout: a temp folder under
// /var is a link on macOS, and refusing it would refuse every test run.
function assertNoLinkedAncestor() {
  const relative = path.relative(REPO_ROOT, OUTPUT_DIR);
  if (!relative || relative === '..' || relative.startsWith('..' + path.sep) || path.isAbsolute(relative)) {
    return;
  }
  let current = REPO_ROOT;
  for (const segment of relative.split(path.sep).slice(0, -1)) {
    current = path.join(current, segment);
    let stat;
    try {
      stat = fs.lstatSync(current);
    } catch (error) {
      if (error.code === 'ENOENT') return;
      throw error;
    }
    if (stat.isSymbolicLink()) {
      throw new Error('refusing to write through a symbolic link at ' + OUTPUT_DIR);
    }
  }
}

function assertOutputDirectorySafe() {
  assertNoLinkedAncestor();
  try {
    const stat = fs.lstatSync(OUTPUT_DIR);
    if (stat.isSymbolicLink()) {
      throw new Error('refusing to write through a symbolic link at ' + OUTPUT_DIR);
    }
    if (!stat.isDirectory()) {
      throw new Error('output path is not a directory: ' + OUTPUT_DIR);
    }
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
}

// ───────────────────────────────────────────────────────────────────
// 4. CORE LOGIC
// ───────────────────────────────────────────────────────────────────

function checkOutputs(expected) {
  const existing = new Set(listOutputFiles());
  const drift = [];

  for (const [outputName, { text }] of expected) {
    const outputPath = path.join(OUTPUT_DIR, outputName);
    if (!existing.has(outputName)) {
      drift.push('MISSING ' + pathLabel(outputPath));
      continue;
    }
    existing.delete(outputName);
    const stat = fs.lstatSync(outputPath);
    if (!stat.isFile() || stat.isSymbolicLink() || fs.readFileSync(outputPath, 'utf8') !== text) {
      drift.push('STALE ' + pathLabel(outputPath));
    }
  }

  for (const outputName of [...existing].sort()) {
    drift.push('EXTRA ' + pathLabel(path.join(OUTPUT_DIR, outputName)));
  }

  if (drift.length > 0) {
    console.error('[vibe-agent-sync] Drift detected:');
    for (const item of drift) console.error('[vibe-agent-sync] ' + item);
    console.error(
      '[vibe-agent-sync] FAIL: ' + drift.length + ' drift item(s); run without --check to regenerate',
    );
    return 1;
  }

  console.log('[vibe-agent-sync] PASS: ' + expected.size + ' agent profiles are in sync.');
  return 0;
}

function removeEntry(entryPath) {
  const stat = fs.lstatSync(entryPath);
  if (stat.isDirectory() && !stat.isSymbolicLink()) {
    fs.rmSync(entryPath, { recursive: true, force: true });
  } else {
    fs.unlinkSync(entryPath);
  }
}

function writeOutputs(expected) {
  assertOutputDirectorySafe();
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  const expectedFiles = new Set(expected.keys());
  let pruned = 0;

  for (const outputName of listOutputFiles()) {
    if (expectedFiles.has(outputName)) continue;
    removeEntry(path.join(OUTPUT_DIR, outputName));
    pruned += 1;
  }

  let written = 0;
  for (const [outputName, { text }] of expected) {
    const outputPath = path.join(OUTPUT_DIR, outputName);
    let stat = null;
    try {
      stat = fs.lstatSync(outputPath);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (stat && (stat.isSymbolicLink() || !stat.isFile())) {
      throw new Error('refusing to replace a non-file output at ' + outputPath);
    }
    const current = stat ? fs.readFileSync(outputPath, 'utf8') : null;
    if (current !== text) {
      fs.writeFileSync(outputPath, text, 'utf8');
      written += 1;
    }
  }

  console.log(
    '[vibe-agent-sync] Wrote ' + written + ' of ' + expected.size + ' agent profiles; pruned ' + pruned + '.',
  );
}

/** Runs the agent profile sync in check or write mode. */
function sync(options) {
  const expected = buildExpectedOutputs();
  if (options.check) return checkOutputs(expected);
  writeOutputs(expected);
  return 0;
}

// ───────────────────────────────────────────────────────────────────
// 5. ENTRYPOINT
// ───────────────────────────────────────────────────────────────────

if (require.main === module) {
  try {
    process.exitCode = sync(parseArguments(process.argv.slice(2)));
  } catch (error) {
    console.error('[vibe-agent-sync] ERROR: ' + error.message);
    process.exitCode = 1;
  }
}

module.exports = {
  sync,
  parseArguments,
  listSourceFiles,
  splitSource,
  tomlString,
  renderAgentProfile,
  buildExpectedOutputs,
};
