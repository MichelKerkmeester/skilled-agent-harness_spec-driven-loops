import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';

const require = createRequire(import.meta.url);
const yaml = require('js-yaml');
const SCRIPT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'dsh',
  'sync-agents-dsh.cjs',
);

function fixture() {
  const root = mkdtempSync(join(tmpdir(), 'dsh-agents-'));
  const source = join(root, 'agents');
  const output = join(root, 'out');
  mkdirSync(source, { recursive: true });
  return { root, source, output };
}

function writeAgent(source, fileName, body) {
  writeFileSync(
    join(source, fileName),
    '---\nname: ' + fileName.replace(/\.md$/, '')
      + '\ndescription: Agent description\n---\n' + body,
  );
}

function run(env, args = []) {
  const result = spawnSync(process.execPath, [SCRIPT, ...args], {
    cwd: env.root,
    encoding: 'utf8',
    env: {
      ...process.env,
      DSH_AGENTS_SOURCE_DIR: env.source,
      DSH_AGENTS_OUTPUT_DIR: env.output,
    },
  });
  if (result.error) throw result.error;
  return { status: result.status, stdout: result.stdout, stderr: result.stderr };
}

test('writes a single system-prompt patch with a YAML block scalar and the full agent body', () => {
  const env = fixture();
  try {
    const body = [
      '# Worker persona',
      '',
      'Keep key: value and "quoted text" intact.',
      '',
      'Last line.',
      '',
    ].join('\n');
    writeAgent(env.source, 'worker.md', body);
    writeAgent(env.source, 'reviewer.md', '# Reviewer\n');
    writeFileSync(join(env.source, 'README.md'), '# Agent index\n');

    const result = run(env);
    assert.equal(result.status, 0, result.stderr);
    assert.match(result.stdout, /Wrote 2 of 2 agent patches/);

    const patchText = readFileSync(join(env.output, 'worker.patch.yml'), 'utf8');
    assert.match(
      patchText.split('\n')[0],
      /^# Generated by sync-agents-dsh\.cjs from \.skilled\/agents\/worker\.md$/,
    );
    assert.match(patchText, /personaPrefix: \|2/);
    const parsed = yaml.load(patchText);
    assert.deepEqual(parsed, [
      {
        id: 'system-prompt',
        config: { personaPrefix: body },
      },
    ]);
    assert.equal(existsSync(join(env.output, 'README.patch.yml')), false);

    const check = run(env, ['--check']);
    assert.equal(check.status, 0, check.stderr);
    assert.match(check.stdout, /PASS: 2 agent patches are in sync/);
  } finally {
    rmSync(env.root, { recursive: true, force: true });
  }
});

test('--check reports missing, stale, and extra agent patches without repairing them', () => {
  const env = fixture();
  try {
    writeAgent(env.source, 'worker.md', '# Worker\n');
    writeAgent(env.source, 'reviewer.md', '# Reviewer\n');
    assert.equal(run(env).status, 0);

    const missing = join(env.output, 'reviewer.patch.yml');
    const stale = join(env.output, 'worker.patch.yml');
    const extra = join(env.output, 'extra.patch.yml');
    unlinkSync(missing);
    writeFileSync(stale, 'stale\n');
    writeFileSync(extra, 'extra\n');

    const check = run(env, ['--check']);
    const output = check.stdout + check.stderr;
    assert.equal(check.status, 1);
    assert.match(output, /MISSING .*reviewer\.patch\.yml/);
    assert.match(output, /STALE .*worker\.patch\.yml/);
    assert.match(output, /EXTRA .*extra\.patch\.yml/);
    assert.equal(existsSync(missing), false);
    assert.equal(readFileSync(stale, 'utf8'), 'stale\n');
    assert.equal(readFileSync(extra, 'utf8'), 'extra\n');

    const repaired = run(env);
    assert.equal(repaired.status, 0, repaired.stderr);
    assert.equal(existsSync(extra), false);
    assert.equal(run(env, ['--check']).status, 0);
  } finally {
    rmSync(env.root, { recursive: true, force: true });
  }
});

test('an empty source list fails without pruning existing agent patches', () => {
  const env = fixture();
  try {
    env.source = join(env.root, 'missing-agents');
    mkdirSync(env.output, { recursive: true });
    const existing = join(env.output, 'existing.patch.yml');
    writeFileSync(existing, 'operator-owned\n');

    const result = run(env);
    assert.equal(result.status, 1);
    assert.match(result.stderr, /no agent sources found/);
    assert.equal(readFileSync(existing, 'utf8'), 'operator-owned\n');
  } finally {
    rmSync(env.root, { recursive: true, force: true });
  }
});
