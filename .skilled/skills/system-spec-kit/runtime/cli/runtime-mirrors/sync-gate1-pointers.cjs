#!/usr/bin/env node
'use strict';
// ───────────────────────────────────────────────────────────────────
// MODULE: Gate 1 pointer synchronizer
// ───────────────────────────────────────────────────────────────────
// The Gate 1 trigger-index lookup instruction lives once, in the root
// AGENTS.md. Claude reads that file directly, Pi loads it from the working
// directory and Codex loads it as project instructions. The Cursor
// rule that Cursor and Devin share is read on its own, so it carries pointer
// blocks generated from the root lines rather than a hand-kept copy. The
// second block carries the Gate 2 command rule and the direct advisor call
// that replaces the per-prompt brief those clients do not receive. Write mode
// rewrites the blocks in place; --check reports drift and writes nothing.
//
// Usage:
//   node sync-gate1-pointers.cjs [--check] [--root <repo-root>]
// Exit: 0 in sync (or written), 1 drift under --check, 2 usage or missing source.

const fs = require('node:fs');
const path = require('node:path');
const { findRepoRoot } = require('@spec-kit/shared/workspace/repo-root.mjs');

const TAG = '[gate1-pointer-sync]';
const START = '<!-- spec-kit:gate1-pointer:start -->';
const END = '<!-- spec-kit:gate1-pointer:end -->';
const START_COMMAND = '<!-- spec-kit:gate2-command-pointer:start -->';
const END_COMMAND = '<!-- spec-kit:gate2-command-pointer:end -->';
const SOURCE_FILE = 'AGENTS.md';
const SOURCE_MARKER = 'lookup-trigger-index.mjs';
const GATE_TWO_CALL_MARKER = 'skill-advisor.cjs advisor_recommend';
const GATE_TWO_COMMAND_MARKER = '**Command in the brief.**';
const GENERATED_BY = 'Generated by `node .skilled/skills/system-spec-kit/runtime/cli/runtime-mirrors/sync-gate1-pointers.cjs`; edit the root `AGENTS.md` line, not this block.';

/** The instruction files that carry generated pointer blocks, relative to the repo root. */
const TARGETS = [
  {
    file: path.join('.cursor', 'rules', 'skill-routing.md'),
    intro: 'Gate 1 of the root `AGENTS.md` applies on every new prompt; before routing to a packet, run the lookup it names:',
    commandIntro: 'Cursor gets no per-prompt advisor brief under the tested build. Before acting, run the direct call below, then apply the command rule:',
  },
];

function parseArgs(argv) {
  const options = { check: false, root: null };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--check') options.check = true;
    else if (arg === '--root') { options.root = argv[index + 1]; index += 1; }
    else throw new Error(`Usage: node sync-gate1-pointers.cjs [--check] [--root <repo-root>] (unknown argument: ${arg})`);
  }
  if (options.root === undefined) throw new Error('--root requires a path');
  return options;
}

/** The first root AGENTS.md line holding the marker, with a leading list number stripped, or null. */
function readMarkedLine(repoRoot, marker) {
  const sourcePath = path.join(repoRoot, SOURCE_FILE);
  if (!fs.existsSync(sourcePath)) return null;
  const line = fs.readFileSync(sourcePath, 'utf8').split(/\r?\n/u).find((candidate) => candidate.includes(marker));
  return line ? line.trim().replace(/^\d+\.\s*/u, '') : null;
}

/** The Gate 1 lookup line as the root AGENTS.md states it, or null when the file carries none. */
function readGateOneLine(repoRoot) {
  return readMarkedLine(repoRoot, SOURCE_MARKER);
}

/** The Gate 1 block each target carries, built from the root line so the two can never disagree. */
function renderBlock(intro, gateOneLine) {
  return [
    START,
    '## Gate 1 lookup (generated from the root AGENTS.md)',
    '',
    intro,
    '',
    gateOneLine,
    '',
    GENERATED_BY,
    END,
  ].join('\n');
}

/** The Gate 2 command block, built from the root call and command lines so the two can never disagree. */
function renderCommandBlock(commandIntro, callLine, commandLine) {
  return [
    START_COMMAND,
    '## Gate 2 command routing (generated from the root AGENTS.md)',
    '',
    commandIntro,
    '',
    callLine,
    '',
    commandLine,
    '',
    GENERATED_BY,
    END_COMMAND,
  ].join('\n');
}

/** The span of a tagged block, or null when either tag is missing or they appear out of order. */
function blockBounds(content, startTag, endTag) {
  const start = content.indexOf(startTag);
  if (start === -1) return null;
  const end = content.indexOf(endTag, start + startTag.length);
  if (end === -1) return null;
  return { start, end: end + endTag.length };
}

function splitBlock(content) {
  const bounds = blockBounds(content, START, END);
  if (bounds === null) return { before: content, block: null, after: '' };
  return {
    before: content.slice(0, bounds.start),
    block: content.slice(bounds.start, bounds.end),
    after: content.slice(bounds.end),
  };
}

/** The file content with the generated block replaced or appended after the existing text. */
function applyBlock(content, block) {
  const parts = splitBlock(content);
  if (parts.block !== null) return `${parts.before}${block}${parts.after}`;
  const trimmed = content.replace(/\s*$/u, '');
  return `${trimmed}\n\n${block}\n`;
}

/** The content without the generated command block, its separator blank line and its own line ending. */
function removeCommandBlock(content) {
  const bounds = blockBounds(content, START_COMMAND, END_COMMAND);
  if (bounds === null) return content;
  const lineStart = content.lastIndexOf('\n', bounds.start - 1) + 1;
  let lineEnd = bounds.end;
  if (content.startsWith('\n', lineEnd)) lineEnd += 1;
  const before = content.slice(0, lineStart);
  const trimmed = before.endsWith('\n\n') ? before.slice(0, -1) : before;
  return `${trimmed}${content.slice(lineEnd)}`;
}

/** The command block as the target carries it, or null when the block is absent. */
function readCommandBlock(content) {
  const bounds = blockBounds(content, START_COMMAND, END_COMMAND);
  return bounds === null ? null : content.slice(bounds.start, bounds.end);
}

/** The content with the command block right after the Gate 1 block, or without it when there is none to write. */
function applyCommandBlock(content, block) {
  const withoutCommand = removeCommandBlock(content);
  if (block === null) return withoutCommand;
  const gateOne = splitBlock(withoutCommand);
  if (gateOne.block === null) return withoutCommand;
  const at = gateOne.before.length + gateOne.block.length;
  const tail = withoutCommand.slice(at).replace(/^\n\n?/u, '');
  return `${withoutCommand.slice(0, at)}\n\n${block}${tail === '' ? '\n' : `\n\n${tail}`}`;
}

function main(argv) {
  const options = parseArgs(argv);
  const repoRoot = options.root ? path.resolve(options.root) : findRepoRoot(__dirname);
  const gateOneLine = readGateOneLine(repoRoot);
  if (!gateOneLine) {
    console.error(`${TAG} ERROR: ${SOURCE_FILE} under ${repoRoot} carries no line naming ${SOURCE_MARKER}`);
    return 2;
  }
  const callLine = readMarkedLine(repoRoot, GATE_TWO_CALL_MARKER);
  const commandLine = readMarkedLine(repoRoot, GATE_TWO_COMMAND_MARKER);

  const drift = [];
  let written = 0;
  for (const target of TARGETS) {
    const targetPath = path.join(repoRoot, target.file);
    if (!fs.existsSync(targetPath)) {
      drift.push(`${target.file}: missing`);
      continue;
    }
    const current = fs.readFileSync(targetPath, 'utf8');
    const gateOneBlock = renderBlock(target.intro, gateOneLine);
    const commandBlock = callLine && commandLine ? renderCommandBlock(target.commandIntro, callLine, commandLine) : null;
    const expected = applyCommandBlock(applyBlock(current, gateOneBlock), commandBlock);
    if (current === expected) continue;
    if (options.check) {
      const driftStart = drift.length;
      const gateOneCurrent = splitBlock(current).block;
      if (gateOneCurrent !== gateOneBlock) {
        drift.push(`${target.file}: ${gateOneCurrent === null ? 'no Gate 1 pointer block' : 'pointer block differs from the root AGENTS.md line'}`);
      }
      const commandCurrent = readCommandBlock(current);
      if (commandCurrent !== commandBlock) {
        drift.push(`${target.file}: ${commandCurrent === null ? 'no Gate 2 command block' : 'pointer block differs from the root AGENTS.md Gate 2 lines'}`);
      }
      if (drift.length === driftStart) drift.push(`${target.file}: pointer block differs from the root AGENTS.md Gate 2 lines`);
      continue;
    }
    fs.writeFileSync(targetPath, expected, 'utf8');
    written += 1;
  }

  if (drift.length > 0) {
    console.error(`${TAG} Drift detected:`);
    for (const item of drift) console.error(`${TAG} ${item}`);
    return 1;
  }
  if (options.check) console.log(`${TAG} PASS: ${TARGETS.length} instruction files carry the root Gate 1 and Gate 2 pointers.`);
  else console.log(`${TAG} Wrote ${written} of ${TARGETS.length} pointer blocks.`);
  return 0;
}

if (require.main === module) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    console.error(`${TAG} ERROR: ${error.message}`);
    process.exitCode = 2;
  }
}

module.exports = {
  TARGETS,
  START,
  END,
  START_COMMAND,
  END_COMMAND,
  GATE_TWO_CALL_MARKER,
  GATE_TWO_COMMAND_MARKER,
  readGateOneLine,
  readMarkedLine,
  renderBlock,
  renderCommandBlock,
  applyBlock,
  applyCommandBlock,
  main,
};
