'use strict';

// ───────────────────────────────────────────────────────────────────
// 1. IMPORTS
// ───────────────────────────────────────────────────────────────────

const fs = require('node:fs');
const path = require('node:path');
const {
  isCanonicalMirrorExcluded,
  isRuntimeNativeCommand,
} = require('../runtime-mirrors/command-scope.cjs');
const { findRepoRoot } = require('@spec-kit/shared/workspace/repo-root.mjs');

// ───────────────────────────────────────────────────────────────────
// 2. CONSTANTS
// ───────────────────────────────────────────────────────────────────

const REPO_ROOT = findRepoRoot(__dirname);
const SOURCE_DIR = path.resolve(
  process.env.DSH_COMMANDS_SOURCE_DIR || path.join(REPO_ROOT, '.skilled', 'commands'),
);
const OUTPUT_DIR = path.resolve(
  process.env.DSH_PROMPTS_OUTPUT_DIR || path.join(REPO_ROOT, '.dsh', 'prompts'),
);
const EXCLUDED_DIRECTORIES = new Set(['assets', 'scripts', 'fixtures']);

// ───────────────────────────────────────────────────────────────────
// 3. HELPERS
// ───────────────────────────────────────────────────────────────────

/** Parses the supported command-line options. */
function parseArguments(argv) {
  if (argv.length === 0) return { check: false };
  if (argv.length === 1 && argv[0] === '--check') return { check: true };
  throw new Error('Usage: node sync-prompts-dsh.cjs [--check]');
}

function toPosix(filePath) {
  return filePath.split(path.sep).join('/');
}

function pathLabel(filePath) {
  const relativePath = path.relative(REPO_ROOT, filePath);
  if (
    relativePath
    && relativePath !== '..'
    && !relativePath.startsWith('..' + path.sep)
    && !path.isAbsolute(relativePath)
  ) {
    return toPosix(relativePath);
  }
  return filePath;
}

/** Lists canonical command files that can be mirrored as DSH prompts. */
function listCommandFiles(directory) {
  if (!fs.existsSync(directory)) return [];

  const relativePaths = [];
  const root = path.resolve(directory);
  const walk = (current) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const absolutePath = path.join(current, entry.name);
      if (entry.isDirectory()) {
        if (!EXCLUDED_DIRECTORIES.has(entry.name)) walk(absolutePath);
        continue;
      }
      if (!entry.isFile() || !entry.name.endsWith('.md')) continue;
      if (entry.name === 'README.md' || entry.name.endsWith('.contract.md')) continue;
      relativePaths.push(toPosix(path.relative(root, absolutePath)));
    }
  };

  walk(root);
  return relativePaths.sort();
}

/** Flattens a command path into the DSH prompt filename. */
function toFlatName(relativePath) {
  return relativePath.replace(/\.md$/, '').split('/').join('-');
}

/** Renders a prompt stub that points back to its canonical command. */
function renderPrompt(relativePath) {
  const flatName = toFlatName(relativePath);
  return [
    '<!-- Generated by sync-prompts-dsh.cjs from .skilled/commands/' + relativePath + '. -->',
    '# DeepSeek Harness prompt: /' + flatName,
    '',
    'This prompt file points to the canonical command definition at .skilled/commands/'
      + relativePath + '.',
    '',
    'Read that file in full and follow its instructions. It defines the command behavior.',
    '',
    'The dsh dispatcher appends the user request below this line.',
    '',
    'User request:',
  ].join('\n') + '\n';
}

/** Builds prompt stubs from the canonical command source tree. */
function buildExpectedOutputs() {
  const sourceFiles = listCommandFiles(SOURCE_DIR)
    .filter((relativePath) => !isCanonicalMirrorExcluded(relativePath));
  if (sourceFiles.length === 0) {
    throw new Error('no canonical commands found in ' + SOURCE_DIR);
  }

  const expected = new Map();
  for (const relativePath of sourceFiles) {
    const outputName = toFlatName(relativePath) + '.md';
    if (expected.has(outputName)) {
      throw new Error(
        'flattened command name "' + outputName + '" collides for '
          + expected.get(outputName).source + ' and ' + relativePath,
      );
    }
    expected.set(outputName, {
      source: relativePath,
      text: renderPrompt(relativePath),
    });
  }
  return expected;
}

// A link here is not this generator's output: a linked worktree reaches the
// operator's private prompts through links to the primary checkout, as the codex
// prompt generator also assumes. Counting one would report it as extra and prune it.
function listOutputFiles() {
  if (!fs.existsSync(OUTPUT_DIR)) return [];
  return fs.readdirSync(OUTPUT_DIR, { withFileTypes: true })
    .filter((entry) => entry.name.endsWith('.md') && entry.isFile())
    .map((entry) => entry.name)
    .sort();
}

function assertOutputDirectorySafe() {
  try {
    const stat = fs.lstatSync(OUTPUT_DIR);
    if (stat.isSymbolicLink()) {
      throw new Error('refusing to write through a symbolic link at ' + OUTPUT_DIR);
    }
    if (!stat.isDirectory()) {
      throw new Error('output path is not a directory: ' + OUTPUT_DIR);
    }
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
}

// ───────────────────────────────────────────────────────────────────
// 4. CORE LOGIC
// ───────────────────────────────────────────────────────────────────

function checkOutputs(expected) {
  const existing = new Set(listOutputFiles());
  const drift = [];

  for (const [outputName, { text }] of expected) {
    const outputPath = path.join(OUTPUT_DIR, outputName);
    if (!existing.has(outputName)) {
      drift.push('MISSING ' + pathLabel(outputPath));
      continue;
    }

    existing.delete(outputName);
    const stat = fs.lstatSync(outputPath);
    if (!stat.isFile() || stat.isSymbolicLink() || fs.readFileSync(outputPath, 'utf8') !== text) {
      drift.push('STALE ' + pathLabel(outputPath));
    }
  }

  for (const outputName of [...existing].sort()) {
    if (isRuntimeNativeCommand('.dsh/prompts', outputName)) continue;
    drift.push('EXTRA ' + pathLabel(path.join(OUTPUT_DIR, outputName)));
  }

  if (drift.length > 0) {
    console.error('[dsh-prompt-sync] Drift detected:');
    for (const item of drift) console.error('[dsh-prompt-sync] ' + item);
    console.error(
      '[dsh-prompt-sync] FAIL: ' + drift.length + ' drift item(s); run without --check to regenerate',
    );
    return 1;
  }

  console.log('[dsh-prompt-sync] PASS: ' + expected.size + ' prompt stubs are in sync.');
  return 0;
}

function writeOutputs(expected) {
  assertOutputDirectorySafe();
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  const expectedFiles = new Set(expected.keys());
  let pruned = 0;

  for (const outputName of listOutputFiles()) {
    if (expectedFiles.has(outputName) || isRuntimeNativeCommand('.dsh/prompts', outputName)) continue;
    fs.unlinkSync(path.join(OUTPUT_DIR, outputName));
    pruned += 1;
  }

  let written = 0;
  for (const [outputName, { text }] of expected) {
    const outputPath = path.join(OUTPUT_DIR, outputName);
    let stat = null;
    try {
      stat = fs.lstatSync(outputPath);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (stat && (stat.isSymbolicLink() || !stat.isFile())) {
      throw new Error('refusing to replace a non-file output at ' + outputPath);
    }
    const current = stat ? fs.readFileSync(outputPath, 'utf8') : null;
    if (current !== text) {
      fs.writeFileSync(outputPath, text, 'utf8');
      written += 1;
    }
  }

  console.log(
    '[dsh-prompt-sync] Wrote ' + written + ' of ' + expected.size + ' prompts; pruned ' + pruned + '.',
  );
}

/** Runs the prompt sync in check or write mode. */
function sync(options) {
  const expected = buildExpectedOutputs();
  if (options.check) return checkOutputs(expected);
  writeOutputs(expected);
  return 0;
}

// ───────────────────────────────────────────────────────────────────
// 5. ENTRYPOINT
// ───────────────────────────────────────────────────────────────────

if (require.main === module) {
  try {
    process.exitCode = sync(parseArguments(process.argv.slice(2)));
  } catch (error) {
    console.error('[dsh-prompt-sync] ERROR: ' + error.message);
    process.exitCode = 1;
  }
}

module.exports = {
  sync,
  parseArguments,
  listCommandFiles,
  toFlatName,
  renderPrompt,
  buildExpectedOutputs,
};
