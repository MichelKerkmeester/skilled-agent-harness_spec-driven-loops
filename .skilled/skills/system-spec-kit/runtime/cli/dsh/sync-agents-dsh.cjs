'use strict';

// ───────────────────────────────────────────────────────────────────
// 1. IMPORTS
// ───────────────────────────────────────────────────────────────────

const fs = require('node:fs');
const path = require('node:path');
const { findRepoRoot } = require('@spec-kit/shared/workspace/repo-root.mjs');

// ───────────────────────────────────────────────────────────────────
// 2. CONSTANTS
// ───────────────────────────────────────────────────────────────────

const REPO_ROOT = findRepoRoot(__dirname);
const SOURCE_DIR = path.resolve(
  process.env.DSH_AGENTS_SOURCE_DIR || path.join(REPO_ROOT, '.skilled', 'agents'),
);
const OUTPUT_DIR = path.resolve(
  process.env.DSH_AGENTS_OUTPUT_DIR || path.join(REPO_ROOT, '.dsh', 'agents'),
);

// ───────────────────────────────────────────────────────────────────
// 3. HELPERS
// ───────────────────────────────────────────────────────────────────

/** Parses the supported command-line options. */
function parseArguments(argv) {
  if (argv.length === 0) return { check: false };
  if (argv.length === 1 && argv[0] === '--check') return { check: true };
  throw new Error('Usage: node sync-agents-dsh.cjs [--check]');
}

function pathLabel(filePath) {
  const relativePath = path.relative(REPO_ROOT, filePath);
  if (
    relativePath
    && relativePath !== '..'
    && !relativePath.startsWith('..' + path.sep)
    && !path.isAbsolute(relativePath)
  ) {
    return relativePath.split(path.sep).join('/');
  }
  return filePath;
}

/** Lists the agent sources that generate DSH persona patches. */
function listSourceFiles(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md') && entry.name !== 'README.md')
    .map((entry) => entry.name)
    .sort();
}

/** Removes frontmatter so the patch carries only the agent body. */
function splitFrontmatter(content) {
  const match = content.match(/^---\r?\n[\s\S]*?\r?\n---(?:\r?\n|$)/);
  if (!match) return content;
  return content.slice(match[0].length);
}

/** Renders agent text as a YAML block scalar without changing its newlines. */
function renderBlockScalar(value) {
  const normalized = value.replace(/\r\n?/g, '\n');
  const trailingMatch = normalized.match(/\n*$/);
  const trailingNewlines = trailingMatch ? trailingMatch[0].length : 0;
  const content = normalized.slice(0, normalized.length - trailingNewlines);
  const contentLines = content === '' ? [] : content.split('\n');
  const indicator = trailingNewlines === 0
    ? '|2-'
    : trailingNewlines === 1
      ? '|2'
      : '|2+';
  const lines = contentLines.map((line) => '      ' + line);
  for (let index = 1; index < trailingNewlines; index += 1) {
    lines.push('      ');
  }
  return { indicator, lines };
}

/** Renders one agent body as a DSH system-prompt patch. */
function renderAgentPatch(fileName, body) {
  const scalar = renderBlockScalar(body);
  const lines = [
    '# Generated by sync-agents-dsh.cjs from .skilled/agents/' + fileName,
    '- id: system-prompt',
    '  config:',
    '    personaPrefix: ' + scalar.indicator,
    ...scalar.lines,
  ];
  return lines.join('\n') + '\n';
}

/** Builds the expected DSH patches from the current agent sources. */
function buildExpectedOutputs() {
  const sourceFiles = listSourceFiles(SOURCE_DIR);
  if (sourceFiles.length === 0) {
    throw new Error('no agent sources found in ' + SOURCE_DIR);
  }
  const expected = new Map();
  for (const fileName of sourceFiles) {
    const sourcePath = path.join(SOURCE_DIR, fileName);
    const body = splitFrontmatter(fs.readFileSync(sourcePath, 'utf8'));
    const outputName = fileName.replace(/\.md$/, '') + '.patch.yml';
    expected.set(outputName, {
      sourcePath,
      text: renderAgentPatch(fileName, body),
    });
  }
  return expected;
}

function listOutputFiles() {
  if (!fs.existsSync(OUTPUT_DIR)) return [];
  return fs.readdirSync(OUTPUT_DIR, { withFileTypes: true })
    .filter((entry) => entry.name.endsWith('.patch.yml'))
    .map((entry) => entry.name)
    .sort();
}

function assertOutputDirectorySafe() {
  try {
    const stat = fs.lstatSync(OUTPUT_DIR);
    if (stat.isSymbolicLink()) {
      throw new Error('refusing to write through a symbolic link at ' + OUTPUT_DIR);
    }
    if (!stat.isDirectory()) {
      throw new Error('output path is not a directory: ' + OUTPUT_DIR);
    }
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
}

// ───────────────────────────────────────────────────────────────────
// 4. CORE LOGIC
// ───────────────────────────────────────────────────────────────────

function checkOutputs(expected) {
  const existing = new Set(listOutputFiles());
  const drift = [];

  for (const [outputName, { text }] of expected) {
    const outputPath = path.join(OUTPUT_DIR, outputName);
    if (!existing.has(outputName)) {
      drift.push('MISSING ' + pathLabel(outputPath));
      continue;
    }
    existing.delete(outputName);
    const stat = fs.lstatSync(outputPath);
    if (!stat.isFile() || stat.isSymbolicLink() || fs.readFileSync(outputPath, 'utf8') !== text) {
      drift.push('STALE ' + pathLabel(outputPath));
    }
  }

  for (const outputName of [...existing].sort()) {
    drift.push('EXTRA ' + pathLabel(path.join(OUTPUT_DIR, outputName)));
  }

  if (drift.length > 0) {
    console.error('[dsh-agent-sync] Drift detected:');
    for (const item of drift) console.error('[dsh-agent-sync] ' + item);
    console.error(
      '[dsh-agent-sync] FAIL: ' + drift.length + ' drift item(s); run without --check to regenerate',
    );
    return 1;
  }

  console.log('[dsh-agent-sync] PASS: ' + expected.size + ' agent patches are in sync.');
  return 0;
}

function removeEntry(entryPath) {
  const stat = fs.lstatSync(entryPath);
  if (stat.isDirectory() && !stat.isSymbolicLink()) {
    fs.rmSync(entryPath, { recursive: true, force: true });
  } else {
    fs.unlinkSync(entryPath);
  }
}

function writeOutputs(expected) {
  assertOutputDirectorySafe();
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  const expectedFiles = new Set(expected.keys());
  let pruned = 0;

  for (const outputName of listOutputFiles()) {
    if (expectedFiles.has(outputName)) continue;
    removeEntry(path.join(OUTPUT_DIR, outputName));
    pruned += 1;
  }

  let written = 0;
  for (const [outputName, { text }] of expected) {
    const outputPath = path.join(OUTPUT_DIR, outputName);
    let stat = null;
    try {
      stat = fs.lstatSync(outputPath);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (stat && (stat.isSymbolicLink() || !stat.isFile())) {
      throw new Error('refusing to replace a non-file output at ' + outputPath);
    }
    const current = stat ? fs.readFileSync(outputPath, 'utf8') : null;
    if (current !== text) {
      fs.writeFileSync(outputPath, text, 'utf8');
      written += 1;
    }
  }

  console.log(
    '[dsh-agent-sync] Wrote ' + written + ' of ' + expected.size + ' agent patches; pruned ' + pruned + '.',
  );
}

/** Runs the agent patch sync in check or write mode. */
function sync(options) {
  const expected = buildExpectedOutputs();
  if (options.check) return checkOutputs(expected);
  writeOutputs(expected);
  return 0;
}

// ───────────────────────────────────────────────────────────────────
// 5. ENTRYPOINT
// ───────────────────────────────────────────────────────────────────

if (require.main === module) {
  try {
    process.exitCode = sync(parseArguments(process.argv.slice(2)));
  } catch (error) {
    console.error('[dsh-agent-sync] ERROR: ' + error.message);
    process.exitCode = 1;
  }
}

module.exports = {
  sync,
  parseArguments,
  listSourceFiles,
  splitFrontmatter,
  renderBlockScalar,
  renderAgentPatch,
  buildExpectedOutputs,
};
