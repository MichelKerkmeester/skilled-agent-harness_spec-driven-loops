'use strict';

// ───────────────────────────────────────────────────────────────────
// 1. IMPORTS
// ───────────────────────────────────────────────────────────────────

const fs = require('node:fs');
const path = require('node:path');

// ───────────────────────────────────────────────────────────────────
// 2. CONSTANTS
// ───────────────────────────────────────────────────────────────────

const { findRepoRoot } = require('@spec-kit/shared/workspace/repo-root.mjs');
const REPO_ROOT = findRepoRoot(__dirname);
const SOURCE_DIR = process.env.HERMES_SKILLS_SOURCE_DIR || path.join(REPO_ROOT, '.opencode', 'skills');
const OUTPUT_DIR = process.env.HERMES_SKILLS_OUTPUT_DIR || path.join(REPO_ROOT, '.hermes', 'skills');
// Hermes has no flag that loads an agent file, and a plugin prompt section is capped at 4000
// characters, so each shared agent persona is also mirrored as a preloadable skill named
// `agent-<name>`: `-s agent-<name>` carries the whole persona into the session.
const AGENTS_DIR = process.env.HERMES_AGENTS_SOURCE_DIR || path.join(REPO_ROOT, '.claude', 'agents');
const AGENT_SKILL_PREFIX = 'agent-';
// Hermes scans every project skill directory with its static security scanner at session start,
// so the generated folder holds one markdown file per skill and nothing the scanner would walk:
// no scripts, no node_modules, no references. The canonical directory is named in the body.
const EXCLUDED_DIRECTORIES = new Set(['node_modules', 'dist', '.state', 'scratch', 'benchmark', 'fixtures', 'z_archive']);
const GENERATED_MARKER = '<!-- generated by sync-skills-hermes.cjs; do not edit -->';

// ───────────────────────────────────────────────────────────────────
// 3. HELPERS
// ───────────────────────────────────────────────────────────────────

function parseArguments(argv) {
  if (argv.length === 0) return { check: false };
  if (argv.length === 1 && argv[0] === '--check') return { check: true };
  throw new Error('Usage: node sync-skills-hermes.cjs [--check]');
}

function listSkillFiles(directory) {
  if (!fs.existsSync(directory)) return [];
  const found = [];
  const walk = (current) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const absolute = path.join(current, entry.name);
      if (entry.isDirectory()) {
        if (!EXCLUDED_DIRECTORIES.has(entry.name)) walk(absolute);
        continue;
      }
      if (entry.isFile() && entry.name === 'SKILL.md') {
        found.push(path.relative(directory, absolute).split(path.sep).join('/'));
      }
    }
  };
  walk(directory);
  return found.sort();
}

function splitFrontmatter(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { frontmatter: null, body: content };
  return { frontmatter: match[1], body: content.slice(match[0].length) };
}

function frontmatterName(frontmatter, fallback) {
  const line = (frontmatter || '').split(/\r?\n/).find((l) => /^name:\s*/.test(l));
  if (!line) return fallback;
  return line.replace(/^name:\s*/, '').trim().replace(/^(["'])(.*)\1$/, '$2') || fallback;
}

function renderSkill(relativePath, content) {
  const { frontmatter, body } = splitFrontmatter(content);
  const skillDir = path.posix.dirname(relativePath);
  const fallbackName = path.posix.basename(skillDir);
  const name = frontmatterName(frontmatter, fallbackName);
  const canonical = `.opencode/skills/${skillDir}`;
  const header = [
    GENERATED_MARKER,
    `> Canonical source: \`${canonical}/\`. This is a generated markdown-only copy so Hermes can load the`,
    `> skill without scanning the canonical directory; read \`references/\`, \`assets/\` and \`scripts/\``,
    `> from the canonical path above.`,
    '',
  ].join('\n');
  const fm = frontmatter === null ? `name: ${name}\ndescription: "${name} skill"` : frontmatter;
  return { name, text: `---\n${fm}\n---\n\n${header}${body}` };
}

function listAgentFiles(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md') && entry.name !== 'README.md')
    .map((entry) => entry.name)
    .sort();
}

function frontmatterField(frontmatter, key) {
  const line = (frontmatter || '').split(/\r?\n/).find((l) => new RegExp(`^${key}:\\s*`).test(l));
  if (!line) return '';
  return line.replace(new RegExp(`^${key}:\\s*`), '').trim().replace(/^(["'])(.*)\1$/, '$2');
}

function renderAgent(fileName, content) {
  const { frontmatter, body } = splitFrontmatter(content);
  const stem = fileName.replace(/\.md$/, '');
  const name = `${AGENT_SKILL_PREFIX}${stem}`;
  const description = frontmatterField(frontmatter, 'description') || `${stem} agent persona`;
  const header = [
    GENERATED_MARKER,
    `> Agent persona \`${stem}\` from \`.hermes/agents/${fileName}\` (the shared agent files), mirrored as a`,
    `> preloadable skill because Hermes has no agent flag. Preload with \`-s ${name}\` and adopt it for the session.`,
    '',
  ].join('\n');
  const escaped = description.replace(/"/g, '\\"');
  return { name, text: `---\nname: ${name}\ndescription: "${escaped}"\n---\n\n${header}${body}` };
}

function listOutputDirs() {
  if (!fs.existsSync(OUTPUT_DIR)) return [];
  return fs.readdirSync(OUTPUT_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() || entry.isSymbolicLink())
    .map((entry) => entry.name)
    .sort();
}

function readIfExists(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}

// ───────────────────────────────────────────────────────────────────
// 4. CORE LOGIC
// ───────────────────────────────────────────────────────────────────

function buildExpected() {
  const expected = new Map();
  for (const relativePath of listSkillFiles(SOURCE_DIR)) {
    const content = fs.readFileSync(path.join(SOURCE_DIR, relativePath), 'utf8');
    const { name, text } = renderSkill(relativePath, content);
    if (expected.has(name)) {
      throw new Error(`duplicate skill name '${name}': ${expected.get(name).source} and ${relativePath}`);
    }
    expected.set(name, { source: relativePath, text });
  }
  for (const fileName of listAgentFiles(AGENTS_DIR)) {
    const content = fs.readFileSync(path.join(AGENTS_DIR, fileName), 'utf8');
    const { name, text } = renderAgent(fileName, content);
    if (expected.has(name)) {
      throw new Error(`agent skill name '${name}' collides with a skill`);
    }
    expected.set(name, { source: `agents/${fileName}`, text });
  }
  return expected;
}

function sync({ check }) {
  const expected = buildExpected();
  const existing = new Set(listOutputDirs());
  const stale = [...existing].filter((name) => !expected.has(name));
  const drift = [];
  for (const [name, { text }] of expected) {
    const target = path.join(OUTPUT_DIR, name, 'SKILL.md');
    const entryPath = path.join(OUTPUT_DIR, name);
    let current = null;
    try {
      // A directory symlink from an earlier layout is replaced by the generated folder.
      if (fs.lstatSync(entryPath).isSymbolicLink()) current = null;
      else current = readIfExists(target);
    } catch {
      current = null;
    }
    if (current !== text) drift.push(name);
  }
  if (check) {
    if (drift.length === 0 && stale.length === 0) {
      console.log(`PASS: ${expected.size} Hermes skill copies in sync`);
      return 0;
    }
    for (const name of drift) console.log(`DRIFT ${name}`);
    for (const name of stale) console.log(`STALE ${name}`);
    console.log(`FAIL: ${drift.length} drifted, ${stale.length} stale; run without --check to regenerate`);
    return 1;
  }
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  for (const name of stale) fs.rmSync(path.join(OUTPUT_DIR, name), { recursive: true, force: true });
  for (const name of drift) {
    const entryPath = path.join(OUTPUT_DIR, name);
    try {
      if (fs.lstatSync(entryPath).isSymbolicLink()) fs.unlinkSync(entryPath);
    } catch { /* absent */ }
    fs.mkdirSync(entryPath, { recursive: true });
    fs.writeFileSync(path.join(entryPath, 'SKILL.md'), expected.get(name).text, 'utf8');
  }
  console.log(`Wrote ${drift.length} of ${expected.size} Hermes skill copies; pruned ${stale.length}`);
  return 0;
}

// ───────────────────────────────────────────────────────────────────
// 5. ENTRYPOINT
// ───────────────────────────────────────────────────────────────────

if (require.main === module) {
  try {
    process.exitCode = sync(parseArguments(process.argv.slice(2)));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 2;
  }
}

module.exports = { sync, renderSkill, renderAgent, listSkillFiles, listAgentFiles, buildExpected };
